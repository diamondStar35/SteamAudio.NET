/// <summary>
/// Specifies requirements that an OpenCL device must meet in order to be considered when listing OpenCL
/// devices.
/// </summary>
[StructLayout(LayoutKind.Sequential)]
public unsafe struct OpenCLDeviceSettings
{
    /// <summary>
    /// The type of device. Set to <c>IPL_OPENCLDEVICETYPE_ANY</c> to consider all available devices.
    /// </summary>
    public OpenCLDeviceType Type;

    /// <summary>
    /// The number of GPU compute units (CUs) that should be reserved for use by Steam Audio. If set to a
    /// non-zero value, then a GPU will be included in the device list only if it can reserve at least this many
    /// CUs. Set to 0 to indicate that Steam Audio can use the entire GPU, in which case all available GPUs will
    /// be considered. Ignored if <c>type</c> is <c>IPL_OPENCLDEVICETYPE_CPU.</c>
    /// </summary>
    public int NumCUsToReserve;

    /// <summary>
    /// The fraction of reserved CUs that should be used for impulse response (IR) update. IR update includes:
    /// a) ray tracing using Radeon Rays to simulate sound propagation, and/or b) pre-transformation of IRs for
    /// convolution using TrueAudio Next. Steam Audio will only list GPU devices that are able to subdivide the
    /// reserved CUs as per this value. The value must be between 0 and 1. For example, if
    /// <c>numCUsToReserve</c> is <c>8</c>, and <c>fractionCUsForIRUpdate</c> is <c>0.5f</c>, then 4 CUs will be
    /// used for IR update and 4 CUs will be used for convolution. Below are typical scenarios: - Using only
    /// TrueAudio Next. Set <c>fractionCUsForIRUpdate</c> to <c>0.5f.</c> This ensures that reserved CUs are
    /// available for IR update as well as convolution. - Using TrueAudio Next and Radeon Rays for real-time
    /// simulation and rendering. Choosing <c>fractionCUsForIRUpdate</c> may require some experimentation to
    /// utilize reserved CUs optimally. You can start by setting <c>fractionCUsForIRUpdate</c> to <c>0.5f.</c>
    /// However, if IR calculation has high latency with these settings, increase <c>fractionCUsForIRUpdate</c>
    /// to use more CUs for ray tracing. - Using only Radeon Rays. Set <c>fractionCUsForIRUpdate</c> to
    /// <c>1</c>, to make sure all the reserved CUs are used for ray tracing. If using Steam Audio for
    /// preprocessing (e.g. baking reverb), then consider setting <c>numCUsToReserve</c> to <c>0</c> to use the
    /// entire GPU for accelerated ray tracing. Ignored if <c>type</c> is <c>IPL_OPENCLDEVICETYPE_CPU</c> or
    /// <c>numCUsToReserve</c> is <c>0.</c>
    /// </summary>
    public float FractionCUsForIRUpdate;

    /// <summary>
    /// If <c>IPL_TRUE</c>, then the GPU device must support TrueAudio Next. It is not necessary to set this to
    /// <c>IPL_TRUE</c> if <c>numCUsToReserve</c> or <c>fractionCUsForIRUpdate</c> are set to non-zero values.
    /// </summary>
    public Bool RequiresTAN;
}

/// <summary>
/// Describes the properties of an OpenCL device. This information can be used to select the most suitable
/// device for your application.
/// </summary>
[StructLayout(LayoutKind.Sequential)]
public unsafe struct OpenCLDeviceDesc
{
    /// <summary>
    /// The OpenCL platform id. Can be cast to <c>cl_platform_id.</c>
    /// </summary>
    public void* Platform;

    /// <summary>
    /// The OpenCL platform name.
    /// </summary>
    public byte* PlatformName;

    /// <summary>
    /// The OpenCL platform vendor's name.
    /// </summary>
    public byte* PlatformVendor;

    /// <summary>
    /// The OpenCL platform version.
    /// </summary>
    public byte* PlatformVersion;

    /// <summary>
    /// The OpenCL device id. Can be cast to <c>cl_device_id.</c>
    /// </summary>
    public void* Device;

    /// <summary>
    /// The OpenCL device name.
    /// </summary>
    public byte* DeviceName;

    /// <summary>
    /// The OpenCL device vendor's name.
    /// </summary>
    public byte* DeviceVendor;

    /// <summary>
    /// The OpenCL device version.
    /// </summary>
    public byte* DeviceVersion;

    /// <summary>
    /// The type of OpenCL device.
    /// </summary>
    public OpenCLDeviceType Type;

    /// <summary>
    /// The number of CUs reserved for convolution. May be <c>0</c> if CU reservation is not supported.
    /// </summary>
    public int NumConvolutionCUs;

    /// <summary>
    /// The number of CUs reserved for IR update. May be <c>0</c> if CU reservation is not supported.
    /// </summary>
    public int NumIRUpdateCUs;

    /// <summary>
    /// The CU reservation granularity. CUs can only be reserved on this device in multiples of this number.
    /// </summary>
    public int Granularity;

    /// <summary>
    /// A relative performance score of a single CU of this device. Only applicable to supported AMD GPUs.
    /// </summary>
    public float PerfScore;
}

