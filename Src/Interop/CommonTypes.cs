using System.Runtime.InteropServices;

namespace SteamAudio.Interop;

/// <summary>
/// Settings used to create a context object.
/// </summary>
[StructLayout(LayoutKind.Sequential)]
public unsafe struct ContextSettings
{
    /// <summary>
    /// The API version used by the caller. Context creation will fail if `phonon.dll` does not implement a
    /// compatible version of the API. Typically, this should be set to `STEAMAUDIO_VERSION`.
    /// </summary>
    public uint Version;

    /// <summary>
    /// (Optional) If non-NULL, Steam Audio will call this function to record log messages generated by certain
    /// operations.
    /// </summary>
    public delegate* unmanaged<LogLevel, byte*, void> LogCallback;

    /// <summary>
    /// (Optional) If non-NULL, Steam Audio will call this function whenever it needs to allocate memory.
    /// </summary>
    public delegate* unmanaged<nuint, nuint, void*> AllocateCallback;

    /// <summary>
    /// (Optional) If non-NULL, Steam Audio will call this function whenever it needs to free memory.
    /// </summary>
    public delegate* unmanaged<void*, void> FreeCallback;

    /// <summary>
    /// The maximum SIMD instruction set level that Steam Audio should use. Steam Audio automatically chooses
    /// the best instruction set to use based on the user's CPU, but you can prevent it from using certain newer
    /// instruction sets using this parameter. For example, with some workloads, AVX512 instructions consume
    /// enough power that the CPU clock speed will be throttled, resulting in lower performance than expected.
    /// If you observe this in your application, set this parameter to `IPL_SIMDLEVEL_AVX2` or lower.
    /// </summary>
    public SimdLevel SimdLevel;

    /// <summary>
    /// Additional flags for modifying the behavior of the created context.
    /// </summary>
    public ContextFlags Flags;
}

