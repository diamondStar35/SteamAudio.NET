/// <summary>
/// Settings used to create an HRTF object.
/// </summary>
[StructLayout(LayoutKind.Sequential)]
public unsafe struct HrtfSettings
{
    /// <summary>
    /// The type of HRTF to create.
    /// </summary>
    public HrtfType Type;

    /// <summary>
    /// SOFA file from which to load HRTF data. Either <c>sofaFileName</c> or <c>sofaData</c> should be
    /// non-NULL. Only for <c>IPL_HRTFTYPE_SOFA.</c>
    /// </summary>
    public byte* SofaFileName;

    /// <summary>
    /// Pointer to a buffer containing SOFA file data from which to load HRTF data. Either <c>sofaFileName</c>
    /// or <c>sofaData</c> should be non-NULL. Only for <c>IPL_HRTFTYPE_SOFA.</c>
    /// </summary>
    public byte* SofaData;

    /// <summary>
    /// Size (in bytes) of the buffer pointed to by <c>sofaData.</c> Only for <c>IPL_HRTFTYPE_SOFA.</c>
    /// </summary>
    public int SofaDataSize;

    /// <summary>
    /// Volume correction factor to apply to the loaded HRTF data. A value of 1.0 means the HRTF data will be
    /// used without any change.
    /// </summary>
    public float Volume;

    /// <summary>
    /// Normalization setting. No normalization will be applied when choosing <c>IPL_HRTFNORMTYPE_NONE.</c>
    /// </summary>
    public HrtfNormType NormType;
}
